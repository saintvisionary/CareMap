const DICTS: Record<Exclude<Lang, "en">, Dict> = { es, fr, zh };

let current: Lang = "en";

export function setLang(lang: Lang): void {
  current = lang;
  if (typeof document !== "undefined") document.documentElement.lang = lang === "zh" ? "zh-Hans" : lang;
}

export function getLang(): Lang {
  return current;
}

/** The phone's language if CareMap has it, else English. */
export function defaultLang(): Lang {
  const nav = typeof navigator !== "undefined" ? navigator.language.toLowerCase() : "en";
  return (["es", "fr", "zh"] as const).find((l) => nav.startsWith(l)) ?? "en";
}

/** Translate English UI text; untranslated text falls back to English. */
export function t(en: string, vars?: Record<string, string | number>): string {
  const s = current === "en" ? en : (DICTS[current][en] ?? en);
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : s;
}

/** "1 person" / "4 people" in the current language. */
export function peopleText(n: number): string {
  return t(n === 1 ? "{n} person" : "{n} people", { n });
}
